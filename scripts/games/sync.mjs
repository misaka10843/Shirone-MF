import {existsSync,mkdirSync,readFileSync,writeFileSync,renameSync} from "node:fs";
import {dirname,join,resolve} from "node:path";
import {parse} from "yaml";
import {resolveContentSource,WORKING_COPY_DIR} from "../content/resolve-source.mjs";
import {normalizeBangumiGame,matchVisualNovel,enrichGame,parseGameSnapshot} from "../../src/utils/game-collection.ts";

const root=process.cwd(), source=resolveContentSource(root);
const contentRoot=source.mode==="external"?(source.source.type==="path"?resolve(root,source.source.path):join(root,WORKING_COPY_DIR)):root;
const configFile=join(contentRoot,"config/games.yaml");
const remote=existsSync(configFile)?parse(readFileSync(configFile,"utf8"))?.remote:undefined;
if (!remote?.bangumi?.enable || !remote.bangumi.userId) {console.log("[games] Remote sync disabled or no Bangumi account configured.");process.exit(0);}
const userId=String(remote.bangumi.userId), output=join(contentRoot,source.mode==="external"?"data/game-snapshots/collection.json":"src/data/game-snapshots/collection.json");
const previous=existsSync(output)?JSON.parse(readFileSync(output,"utf8")):null;
const oldItems=parseGameSnapshot(previous,userId);
const ua="MisakaHome/1.0 (https://github.com/misaka10843/Shirone-MF)";

async function json(url,body) {
 const response=await fetch(url,{method:body?"POST":"GET",headers:{"User-Agent":ua,...(body?{"Content-Type":"application/json"}:{})},body:body?JSON.stringify(body):undefined,signal:AbortSignal.timeout(15000)});
 if(!response.ok)throw new Error(`HTTP ${response.status} (${new URL(url).hostname})`);
 if(!response.headers.get("content-type")?.includes("json"))throw new Error("Expected JSON");
 const reader=response.body.getReader();let length=0;const chunks=[];
 for(;;){const {done,value}=await reader.read();if(done)break;length+=value.length;if(length>5*1024*1024){await reader.cancel();throw new Error("Response exceeds 5 MB");}chunks.push(value);}
 return JSON.parse(Buffer.concat(chunks).toString("utf8"));
}
try {
 const rows=[];let total=Infinity;
 for(let offset=0;offset<total;offset+=50){
  if(offset>=10000)throw new Error("Collection exceeds 10,000 items; refusing partial snapshot");
  const result=await json(`https://api.bgm.tv/v0/users/${encodeURIComponent(userId)}/collections?subject_type=4&limit=50&offset=${offset}`);
  if(!Array.isArray(result.data)||!Number.isSafeInteger(result.total)||result.total<0)throw new Error("Invalid Bangumi response");
  total=result.total;rows.push(...result.data);
  if(!result.data.length&&offset<total)throw new Error("Incomplete Bangumi pagination");
 }
 let items=rows.map(normalizeBangumiGame).filter(Boolean);
 if(items.length!==rows.length)throw new Error("Invalid collection entries; retaining last snapshot");
 items=[...new Map(items.map(item=>[item.id,item])).values()];
 if(!items.length&&oldItems.length)throw new Error("Empty collection; keeping last successful snapshot");
 let matches=0, limited=false;
 if(remote.vndb?.enable){
  const oldById=new Map(oldItems.map(item=>[item.id,item]));
  for(let index=0;index<items.length;index++){
   const game=items[index], old=oldById.get(game.id), subject=rows.find(row=>Number(row.subject?.id)===Number(game.id.slice(4)))?.subject;
   const override=remote.vndb.matches?.[game.id.slice(4)];
   if(override&&!/^v[1-9]\d*$/.test(override))throw new Error("Invalid VNDB override ID");
   // Keep validated prior enrichment while the source is unchanged. --refresh-vndb refreshes it.
   if(old?.sources?.vndb&&!process.argv.includes("--refresh-vndb")&&(!override||old.sources.vndb.endsWith(`/${override}`))){items[index]={...game,developer:old.developer,category:"visual-novel",sources:{...game.sources,vndb:old.sources.vndb}};matches++;continue;}
   if(limited)continue;
   try {
    const names=[subject?.name,subject?.name_cn,game.name].filter(v=>typeof v==="string"&&v.trim());
    const filters=override?["id","=",override]:["search","=",names[0]];
    const result=await json("https://api.vndb.org/kana/vn",{filters,fields:"title,titles.title,titles.latin,aliases,developers.name",results:20});
    if(!Array.isArray(result.results))throw new Error("Invalid VNDB response");
    // A truncated candidate set cannot establish uniqueness.
    const vn=!result.more?matchVisualNovel(result.results,names,override):null;
    if(vn){items[index]=enrichGame(game,vn);matches++;}
    await new Promise(resolve=>setTimeout(resolve,2000));
   }catch(error){console.warn(`[games] VNDB unavailable; retaining Bangumi data: ${error.message}`);limited=true;}
  }
 }
 const snapshot={schemaVersion:1,accountRef:userId,fetchedAt:new Date().toISOString(),items};
 mkdirSync(dirname(output),{recursive:true});const temporary=output+".tmp";
 writeFileSync(temporary,JSON.stringify(snapshot,null,2)+"\n");renameSync(temporary,output);
 writeFileSync(join(dirname(dirname(output)),"gameCollection.ts"),'// Generated by games:sync; collection JSON is the versioned source.\nimport snapshot from "./game-snapshots/collection.json";\nexport const gameCollection: unknown = snapshot;\n');
 console.log(`[games] Saved ${items.length} Bangumi games, ${matches} VNDB matches.`);
}catch(error){console.warn(`[games] Sync failed; previous snapshot kept: ${error.message}`);if(!oldItems.length)process.exitCode=1;}
